/**
 * `/glossary` — the furniture around the published glossary (#1289, register row WEB-07).
 *
 * **The terms are not here, on purpose.** They are `docs/glossary.md`, which
 * `scripts/gen-glossary.mjs` regenerates from the schema comments in `content/` and which
 * `pnpm glossary:check` holds current in every gate lane. The page reads that document at request
 * time (`lib/docs/tree.ts::readDocDocument`) and shapes it with `lib/glossary.ts`, so this file
 * owns only what a *page* says — its title, its lede, the label over the term count, the word
 * in front of each source file, and the sentence a reader gets when the document cannot be read.
 *
 * That split is the card's constraint and the repo's rule at once: a term list copied into a
 * fixture here would be a second register, and the schema comment would no longer be the only
 * place a definition is written.
 *
 * E23 budget 0 for the route: every reader-visible string in `components/glossary/**` is resolved
 * from this fixture by id, and the view holds none of its own.
 */
import { zPageCopy, type PageCopy } from "../../content/pages";

export const glossaryPageCopy: PageCopy = zPageCopy.parse({
  heading: "Glossary",
  /**
   * The lede says where the words come from, because that is the page's one unusual claim: every
   * definition on it is the comment on the schema it describes, not prose written for the site.
   */
  subtitle:
    "The words this product uses, each defined by the comment on the schema that carries it. The documentation's glossary is the register; this page publishes it unchanged.",
  /**
   * The two strings no band owns: the word in front of a source file, and the title over the term
   * index. `term-count` fills `{count}` with the number of terms the document parsed — a number
   * derived from the file, never typed.
   */
  items: [
    { id: "source", label: "Source" },
    { id: "term-index", label: "Terms" },
  ],
  sections: [
    {
      id: "term-count",
      body: "{count} terms, in the order the document defines them.",
    },
    {
      /**
       * Drawn in place of the term list when `docs/glossary.md` is missing or no longer parses.
       * It names the file and the generator rather than apologising: the reader is told what is
       * wrong and the next person is told what to run.
       */
      id: "document-unavailable",
      body: "The glossary document could not be read, so there are no terms to show. It is docs/glossary.md, generated by pnpm glossary from the comments in content/ — the documentation page carries the same words in the meantime.",
    },
  ],
});
