/**
 * Reading the three sources behind `/admin/settings` — the only place they are opened (#1443).
 *
 * **Server-only, and it says so.** This is the one module in the feature that touches `fs`; a
 * `"use client"` module that value-imports it fails `data:check` E34 (the browser graph has no
 * `node:fs`, so the route 500s at request time while `next build` stays green). The module-scope
 * guard below is the same marker `lib/admin/crud-matrix-file.ts` carries.
 *
 * **Three reads, three provenances, and the page prints which is which.**
 *
 *   - the table — `scripts/env-manifest.ts`'s `ENV_ROWS` and `OUT_OF_SCOPE`, *imported*, because it
 *     is the one source of truth and a copy of it would be the defect this page exists to end;
 *   - the census — `docs/operations/env-stores.md`, generated by `pnpm env:matrix --write`, opened
 *     and parsed. It is a **snapshot**: it carries its own `Generated <date>`, which the page prints
 *     beside every count, because a count without its date reads as live;
 *   - the ledger — `data/env/rotations.json`, dates and names only.
 *
 * **Nothing here is fetched and nothing is probed.** `env:matrix` needs a BWS token and a Vercel
 * session that CI does not have, so the census on disk is the only honest answer at request time;
 * a deployment with no census draws the panel that says *not measured in this deployment*, which is
 * a different sentence from *0 findings* and from *not checked*. `docs/specs/settings-integrations.md`
 * §4 band 3 and §7 are the rule.
 *
 * **Read at request time, never at build.** The page is `force-dynamic`, so an edited census or
 * ledger is live on the next request with no rebuild, and `pnpm build` needs neither file — a build
 * with no `docs/` is a green build and an honest page.
 *
 * **A missing or malformed file is a named failure, never a partial read.** `SettingsUnreadable`
 * carries the reason the panel prints; a half-parsed matrix rendered as a table would claim the
 * census checked a name it never saw.
 *
 * Node-only (`node:fs`), reached from the server page and from no client graph.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

import {
  type CensusRow,
  type CensusSnapshot,
  type RotationSet,
  type SettingsDirectory,
  type SettingsInput,
  type SettingsIntegration,
  buildDirectory,
} from "@/lib/admin/settings/providers";
import { OUT_OF_SCOPE, ENV_ROWS } from "@/scripts/env-manifest";

if (typeof window !== "undefined") {
  throw new Error(
    "lib/admin/settings/read.ts is server-only: it reads the store census and the rotation ledger. Read the directory in the page and pass it down as props.",
  );
}

/** The page's address — one constant, so the page, the pill and the tests cannot disagree. */
export const ADMIN_SETTINGS_PATH = "/admin/settings";

/** The census, repo-relative. Printed verbatim in the failure panel — a reader is told *which* file. */
export const SETTINGS_CENSUS_PATH = "docs/operations/env-stores.md";

/** The rotation ledger, repo-relative. Names and dates only, never a value. */
export const SETTINGS_ROTATIONS_PATH = "data/env/rotations.json";

/** A read that could not produce a truthful answer. The page draws one panel naming the reason. */
export class SettingsUnreadable extends Error {
  constructor(readonly reason: string) {
    super(`settings: ${reason}`);
    this.name = "SettingsUnreadable";
  }
}

/** One markdown table: its header cells and its body rows, all trimmed and `|`-split. */
interface MarkdownTable {
  readonly header: readonly string[];
  readonly rows: readonly (readonly string[])[];
}

/** Every markdown table in a document, in the order they appear. Fenced code is not a table. */
function tablesOf(text: string): MarkdownTable[] {
  const tables: MarkdownTable[] = [];
  let header: string[] | null = null;
  let rows: string[][] = [];
  let inFence = false;

  const flush = (): void => {
    if (header !== null && rows.length > 0) tables.push({ header, rows });
    header = null;
    rows = [];
  };

  for (const line of text.split("\n")) {
    const trimmed = line.trim();
    if (trimmed.startsWith("```")) {
      inFence = !inFence;
      continue;
    }
    if (inFence || !trimmed.startsWith("|")) {
      if (!trimmed.startsWith("|")) flush();
      continue;
    }
    const cells = trimmed
      .replace(/^\|/, "")
      .replace(/\|$/, "")
      .split("|")
      .map((cell) => cell.trim());
    if (cells.every((cell) => /^:?-{2,}:?$/.test(cell))) continue; // the separator row
    if (header === null) {
      header = cells;
      continue;
    }
    rows.push(cells);
  }
  flush();
  return tables;
}

/**
 * The census, parsed.
 *
 * **Two tables matter.** The matrix (`name` plus one column per store plus `row`) is what the
 * presence badges read; the findings table (`finding` → `number`) is what the panel under the cards
 * prints, and it is the reason this page can say "6 vault keys no row names" without counting
 * anything itself. Both are read by their **header names**, never by position: the generator has
 * already widened the matrix once, and a positional read would silently compare `.env.example` to
 * production.
 *
 * The date is the document's own — the `Generated <date>` line inside the volatile block. A census
 * with no date is refused: every count on this page is qualified by it.
 */
export function parseCensus(text: string): CensusSnapshot {
  const generated = /^Generated\s+(\d{4}-\d{2}-\d{2})/m.exec(text);
  if (generated === null) {
    throw new SettingsUnreadable(
      `${SETTINGS_CENSUS_PATH} carries no "Generated <date>" line, so every count on this page would print without its date`,
    );
  }
  const storesMatch = /(\d+)\s+name\(s\)\s+across\s+(\d+)\s+store\(s\)/.exec(text);
  // The project-level vault line, and the one honest answer to "could this deployment read the
  // vault at all". A census written without it (a run whose BWS token failed) is not a census that
  // read zero secrets — it is a census that could not read the store, and every vault badge says so.
  const vaultMatch = /Vault:\s*(\d+)\s+secret\(s\)\s+readable/.exec(text);

  const matrix = tablesOf(text).find(
    (table) =>
      table.header.includes("name") &&
      table.header.includes("row") &&
      table.header.some((cell) => cell.startsWith(".env")),
  );
  if (matrix === undefined) {
    throw new SettingsUnreadable(
      `${SETTINGS_CENSUS_PATH} has no matrix table (a header naming name, a store column and row)`,
    );
  }

  const nameIndex = matrix.header.indexOf("name");
  const rowIndex = matrix.header.indexOf("row");
  const storeColumns = matrix.header
    .map((cell, index) => ({ cell, index }))
    .filter((entry) => entry.cell.startsWith(".env") || entry.cell === "BWS");

  const names: CensusRow[] = matrix.rows.map((cells) => {
    const name = (cells[nameIndex] ?? "").replace(/`/g, "");
    const cellsByStore: Record<string, string> = {};
    for (const column of storeColumns) cellsByStore[column.cell] = cells[column.index] ?? "?";
    return { name, cells: cellsByStore, declaredByRow: (cells[rowIndex] ?? "") === "yes" };
  });

  const findingsTable = tablesOf(text).find((table) => table.header[0] === "finding");
  const findings =
    findingsTable?.rows.map((cells) => ({
      finding: cells[0] ?? "",
      count: Number.parseInt((cells[1] ?? "0").replace(/`/g, ""), 10) || 0,
    })) ?? [];

  return {
    recordedAt: generated[1] ?? "",
    names,
    findings,
    stores: storesMatch === null ? storeColumns.length : Number.parseInt(storesMatch[2] ?? "0", 10),
    vaultReadable: vaultMatch === null ? null : Number.parseInt(vaultMatch[1] ?? "0", 10),
  };
}

/** The ledger, validated. A rotation with no date is refused rather than printed as old. */
export function parseRotations(text: string): RotationSet[] {
  let raw: unknown;
  try {
    raw = JSON.parse(text);
  } catch {
    throw new SettingsUnreadable(`${SETTINGS_ROTATIONS_PATH} is not valid JSON`);
  }
  const rotations = (raw as { rotations?: unknown }).rotations;
  if (!Array.isArray(rotations)) {
    throw new SettingsUnreadable(`${SETTINGS_ROTATIONS_PATH} carries no rotations array`);
  }
  return rotations.map((entry, index) => {
    const record = entry as Record<string, unknown>;
    const id = record.id;
    const changedAt = record.changedAt;
    if (typeof id !== "string" || typeof changedAt !== "string") {
      throw new SettingsUnreadable(
        `${SETTINGS_ROTATIONS_PATH} rotation ${index} names no id or no changedAt date`,
      );
    }
    const list = (value: unknown): string[] =>
      Array.isArray(value) ? value.filter((item): item is string => typeof item === "string") : [];
    return {
      id,
      changedAt,
      why: typeof record.why === "string" ? record.why : "",
      names: list(record.names),
      platform: list(record.platform),
      prefixes: list(record.prefixes),
    };
  });
}

/** A file read that turns a missing or unreadable file into the panel's sentence. */
function readText(path: string, what: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch {
    throw new SettingsUnreadable(
      `${what} is not present in this tree, so this request could not read it`,
    );
  }
}

/**
 * The page's facts: the table, the census and the ledger, or the reason one of them could not be
 * read.
 *
 * **The registry is an argument (spec §5a).** `readSettingsDirectory(integrations, …)` is handed the
 * list rather than importing `data/integrations.ts`, so the same reader serves the next expression of
 * the core with a different registry; the tables it *reads* are this tree's manifest, and the two
 * paths are this tree's files. The paths are parameters because the repo's other committed readers
 * resolve from `process.cwd()` (`lib/admin/crud-matrix-file.ts`, `lib/docs/tree.ts`) and a test has to
 * be able to drive real files without writing into `docs/`.
 */
export function readSettingsDirectory(
  integrations: readonly SettingsIntegration[],
  options: {
    readonly censusPath?: string;
    readonly rotationsPath?: string;
  } = {},
): SettingsDirectory {
  const censusPath = options.censusPath ?? join(process.cwd(), SETTINGS_CENSUS_PATH);
  const rotationsPath = options.rotationsPath ?? join(process.cwd(), SETTINGS_ROTATIONS_PATH);
  const census = parseCensus(readText(censusPath, SETTINGS_CENSUS_PATH));
  const rotations = parseRotations(readText(rotationsPath, SETTINGS_ROTATIONS_PATH));

  const input: SettingsInput = {
    integrations,
    rows: ENV_ROWS,
    outOfScope: OUT_OF_SCOPE,
    census,
    rotations,
  };
  return buildDirectory(input);
}

/**
 * The directory derived from the tables alone — no census, no ledger, no filesystem.
 *
 * This is the shape a *deployment without a census* renders: every variable, every provider and
 * every declared flag are the manifest's, presence is `unknown` everywhere, freshness is `not
 * measured` and validity is `not measured` rather than a claim. It exists as a named export so a
 * test renders the real derivation rather than a fixture that could drift from it.
 */
export function readSettingsTablesOnly(
  integrations: readonly SettingsIntegration[],
): SettingsDirectory {
  return buildDirectory({
    integrations,
    rows: ENV_ROWS,
    outOfScope: OUT_OF_SCOPE,
    census: null,
    rotations: [],
  });
}
